"""Freeze contract (protocol v1.0 sections 2, 6, 9). Gold-free: hashes configs/prompts/schemas and the split's
(id, repo, split) triples; never reads gold fields. Imported by the test runner, the dev freezer and the evaluator.

configs/FROZEN.txt is `key: value` lines (comments start with #). artifacts/frozen_params.json holds the numbers;
FROZEN.txt carries its SHA-256, so editing either after the freeze is detected.
"""
import hashlib, json, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FROZEN_TXT = ROOT / "configs/FROZEN.txt"
FROZEN_JSON = ROOT / "artifacts/frozen_params.json"
HASHED = ("configs/models.yaml", "configs/repos.yaml", "configs/prompts/*.txt", "schemas/*.json")
HEDGE_AGENT_ORDER = ("trace", "graph", "spec", "static", "semantic")  # == src.agents.prompts.AGENTS (tested)
CODE_PATHS = ("src", "configs/models.yaml", "configs/repos.yaml", "configs/prompts", "schemas")
REQUIRED_KEYS = ("code_commit", "frozen_params_sha256", "config_hashes_sha256", "model_revision", "dtype", "eta",
                 "hedge_weights", "temperatures_sha256", "protocol", "split_manifest_sha256", "placebo_seed")


class FreezeError(RuntimeError):
    pass


def sha256_bytes(b):
    return hashlib.sha256(b).hexdigest()


def sha256_file(p):
    return sha256_bytes(Path(p).read_bytes())


def config_hashes(root=ROOT):
    out = {}
    for pat in HASHED:
        for p in sorted(root.glob(pat)):
            out[str(p.relative_to(root))] = sha256_file(p)
    return out


def split_manifest(root=ROOT):
    """Sorted (id, repo, split) for every MarketBugs dev/test instance. Reads only those three fields."""
    rows = []
    for split in ("dev", "test"):
        for p in sorted((root / "data/marketbugs" / split).glob("*.jsonl")):
            if p.name == "eval_only.jsonl":
                continue
            for line in open(p):
                r = json.loads(line)
                rows.append((r["id"], r["repo"], r["split"]))
    return sorted(rows)


def split_manifest_hash(root=ROOT):
    return sha256_bytes(json.dumps(split_manifest(root)).encode())


def git(*args, root=ROOT):
    return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)


def head_sha(root=ROOT):
    r = git("rev-parse", "HEAD", root=root)
    return r.stdout.strip() if r.returncode == 0 else None


def tree_clean(paths=CODE_PATHS, root=ROOT):
    r = git("status", "--porcelain", "--", *paths, root=root)
    return r.returncode == 0 and not r.stdout.strip()


def parse_frozen_txt(text):
    kv = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        k, v = line.split(":", 1)
        kv[k.strip()] = v.strip()
    return kv


def render_frozen_txt(params, params_sha):
    lines = ["# MarketBugs frozen evaluation contract (protocol v1.0). Generated by src.analysis.freeze_dev.",
             "# Do not edit by hand: src.agents.run_test and src.analysis.evaluate_test verify every field."]
    w = params["hedge_weights"]  # rendered in canonical agent order: the JSON is saved with sorted keys
    kv = {"code_commit": params["code_commit"], "frozen_params_sha256": params_sha,
          "config_hashes_sha256": params["config_hashes_sha256"], "model_revision": params["model"]["revision_full"],
          "dtype": params["model"]["dtype"], "protocol": params["protocol"], "eta": params["eta"],
          "hedge_weights": ",".join(f"{a}={w[a]:.10g}" for a in HEDGE_AGENT_ORDER),
          "temperatures_sha256": sha256_bytes(json.dumps(params["temperatures"], sort_keys=True).encode()),
          "split_manifest_sha256": params["split_manifest_sha256"], "placebo_seed": params["placebo_seed"],
          "bootstrap_seed": params["bootstrap_seed"], "condition": params["condition"]}
    return "\n".join(lines + [f"{k}: {v}" for k, v in kv.items()]) + "\n"


def load_frozen(root=ROOT, txt=None, js=None):
    """Returns (params, kv). Raises FreezeError if FROZEN.txt is empty/incomplete or does not match the JSON."""
    txt, js = Path(txt or root / "configs/FROZEN.txt"), Path(js or root / "artifacts/frozen_params.json")
    kv = parse_frozen_txt(txt.read_text()) if txt.exists() else {}
    missing = [k for k in REQUIRED_KEYS if k not in kv or not kv[k]]
    if missing:
        raise FreezeError(f"{txt} is empty or incomplete (missing {missing}); run src.analysis.freeze_dev after G2")
    if not js.exists():
        raise FreezeError(f"{js} missing")
    if sha256_file(js) != kv["frozen_params_sha256"]:
        raise FreezeError("frozen_params.json does not match the SHA-256 recorded in FROZEN.txt")
    params = json.loads(js.read_text())
    if render_frozen_txt(params, kv["frozen_params_sha256"]).strip() != txt.read_text().strip():
        raise FreezeError("FROZEN.txt fields disagree with frozen_params.json")
    return params, kv


def verify_frozen(root=ROOT, require_git=True, txt=None, js=None):
    """Full pre-inference gate: frozen files present and consistent, configs/prompts/split unchanged since the
    freeze, and (require_git) the freeze files are committed and code is unchanged since the frozen commit."""
    params, kv = load_frozen(root, txt, js)
    ch = config_hashes(root)
    if sha256_bytes(json.dumps(ch, sort_keys=True).encode()) != params["config_hashes_sha256"]:
        diff = sorted(k for k in set(ch) | set(params["config_hashes"]) if ch.get(k) != params["config_hashes"].get(k))
        raise FreezeError(f"config/prompt/schema files changed since freeze: {diff}")
    if split_manifest_hash(root) != params["split_manifest_sha256"]:
        raise FreezeError("split manifest changed since freeze")
    if require_git:
        for f in ("configs/FROZEN.txt", "artifacts/frozen_params.json"):
            r = git("status", "--porcelain", "--", f, root=root)
            if r.stdout.strip() or git("ls-files", "--error-unmatch", f, root=root).returncode:
                raise FreezeError(f"{f} must be committed before test inference")
        if git("merge-base", "--is-ancestor", params["code_commit"], "HEAD", root=root).returncode:
            raise FreezeError(f"HEAD does not descend from frozen code commit {params['code_commit']}")
        r = git("diff", "--name-only", params["code_commit"], "HEAD", "--", *CODE_PATHS, root=root)
        if r.stdout.strip():
            raise FreezeError(f"code/config changed since frozen commit: {r.stdout.split()}")
        if not tree_clean(root=root):
            raise FreezeError("uncommitted changes under src/configs/schemas")
    return params, kv
